const img = (seed: string, alt: string) => ({ url: `https://picsum.photos/seed/${seed}/800/1067`, alt });

function build(
  partial: Omit<DemoProduct, "id" | "images" | "sareeLength" | "blousePiece" | "careInstructions" | "lowStockThreshold" | "variants" | "createdAtOffsetDays"> &
    Partial<Pick<DemoProduct, "sareeLength" | "blousePiece" | "careInstructions" | "lowStockThreshold" | "variants" | "createdAtOffsetDays">>,
): DemoProduct {
  return {
    ...partial,
    id: partial.slug,
    sareeLength: partial.sareeLength ?? "5.5 m with blouse piece",
    blousePiece: partial.blousePiece ?? "Unstitched blouse piece included",
    careInstructions: partial.careInstructions ?? "Dry clean recommended.",
    lowStockThreshold: partial.lowStockThreshold ?? 2,
    variants: partial.variants ?? [],
    createdAtOffsetDays: partial.createdAtOffsetDays ?? 30,
    images: partial.images ?? [img(partial.slug, `${partial.name} — THE VELORA`), img(`${partial.slug}-2`, `${partial.name} — drape detail`)],
  };
}

